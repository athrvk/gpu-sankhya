"""Devanagari Marathi language pack (mr_deva).

Mirrors hi_deva's structure. Three things are specific to Marathi and are
expressed through generic LanguagePack hooks rather than one-off code:

1. FUSED HUNDREDS. Marathi writes 200..9900 as a cardinal with the bound
   suffix "शे" glued on with no space (दोनशे, अठराशे, साडेतीनशे, दीडशे).
   "शे" is modelled as an ordinary UNIT_SAU surface form and listed in
   `glue_unit_forms`, which tells the generator it may only appear glued
   to a preceding CARD_*/PFX_* word (and the corpus tokenizer how to split
   such a word back into two tokens). The standalone form is शंभर.

2. FUSED PREFIXES. साडे/पावणे are usually typed as one word with their
   cardinal (साडेतीन, पावणेदोन) but also split (साडे तीन). Listed in
   `fused_prefix_forms`; the generator glues them with that probability.

3. CASE SUFFIXES. Marathi inflects unit/cardinal words for case
   (हजारात, लाखांचा, कोटींची, तीसच, साठमध्ये). `word_suffixes` (plus the
   oblique stems in `word_oblique_endings`) let the corpus tokenizer strip
   them and still recognise the head word; the suffix characters stay part
   of that word's token, so the whole word carries the unit/cardinal class.
"""
